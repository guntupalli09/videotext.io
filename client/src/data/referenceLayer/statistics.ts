function rejected(
  id: string,
  claim: string,
  sourceUrl: string | undefined,
  rejectReason: string,
): StatisticCandidate {
  return {
    id,
    status: 'rejected',
    category: 'rejected-unverified',
    claim,
    sourceUrl,
    rejectReason,
  }
}

export function getRetainedStatistics(): StatisticCandidate[] {
  return STATISTIC_CANDIDATES.filter((item) => item.status === 'retained')
}

export function getRejectedStatistics(): StatisticCandidate[] {
  return STATISTIC_CANDIDATES.filter((item) => item.status === 'rejected')
}

export function getCandidateCount(): number {
  return STATISTIC_CANDIDATES.length
}

export function getRetainedByCategory(): Map<string, StatisticCandidate[]> {
  const map = new Map<string, StatisticCandidate[]>()
  for (const item of getRetainedStatistics()) {
    const list = map.get(item.category) ?? []
    list.push(item)
    map.set(item.category, list)
  }
  return map
}

export function getUniqueSourceOrganizations(): string[] {
  return [...new Set(getRetainedStatistics().map((item) => item.sourceOrganization).filter(Boolean))] as string[]
}

export function getUniqueSourceUrls(): string[] {
  return [...new Set(getRetainedStatistics().map((item) => item.sourceUrl).filter(Boolean))] as string[]
}
